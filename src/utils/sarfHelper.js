// Lookup Sarf data for any word or sentence
export function getSarfDataForWord(arabicText, bengaliText = '') {
  if (!arabicText) return null;

  const rawWords = arabicText.trim().split(/\s+/);
  const normalizedWords = rawWords.map(w => normalizeWord(w));

  // 1. Direct match on any word token
  for (const entry of SARF_DATABASE) {
    for (const key of entry.keys) {
      const normKey = normalizeWord(key);
      if (normalizedWords.includes(normKey)) {
        return entry;
      }
    }
  }

  // 2. Partial substring match for roots
  for (const entry of SARF_DATABASE) {
    for (const key of entry.keys) {
      const normKey = normalizeWord(key);
      if (normKey.length >= 3) {
        for (const nw of normalizedWords) {
          if (nw === normKey || (nw.length > normKey.length && nw.includes(normKey))) {
            return entry;
          }
        }
      }
    }
  }

  return null;
}
