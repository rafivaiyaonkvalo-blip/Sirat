import { stripHarakat } from './tarkibHelper';

// Normalize for search: strip harakat, alif variants, and leading 'ال'
function normalizeWord(text) {
  if (!text) return '';
  let clean = stripHarakat(text).trim().toLowerCase();
  clean = clean.replace(/^[والف]+/, (match) => {
    // If word starts with 'ال', strip it for base root matching
    if (clean.startsWith('ال') && clean.length > 3) {
      return clean.slice(2);
    }
    return match;
  });
  if (clean.startsWith('ال') && clean.length > 3) {
    clean = clean.slice(2);
  }
  return clean;
}

