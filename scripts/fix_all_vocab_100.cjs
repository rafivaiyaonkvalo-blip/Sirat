// Apply fixes to all items
let overrideCount = 0;
let regexFixCount = 0;

const updatedVocab = vocab.map(item => {
  let ar = item.arabic.trim();
  let bn = item.bengali.trim();
  let tr = item.transliteration;
  let pos = item.partOfSpeech;

  // 1. Check ID override
  if (EXACT_ID_OVERRIDES[item.id]) {
    const o = EXACT_ID_OVERRIDES[item.id];
    ar = o.ar;
    bn = o.bn;
    if (o.tr) tr = o.tr;
    if (o.pos) pos = o.pos;
    overrideCount++;
  } else {
    // 2. Normalize Arabic formatting
    // Clean spaces around tanween
    ar = ar.replace(/\s*-\s*([^\s]+)/g, ' - $1');
    ar = ar.replace(/\s*ٌ\s*/g, 'ٌ');
    ar = ar.replace(/ٌ+/g, 'ٌ');

    // Fix paren attached in Arabic: e.g. "فِيْل(مؤنث" -> "فِيْلٌ (مُؤَنَّث)"
    if (/[\u0600-\u06FF]\(/.test(ar)) {
      ar = ar.replace(/([\u0600-\u06FF])\(/g, '$1 (');
    }
    // Fix unclosed parenthesis
    if (ar.includes('(') && !ar.includes(')')) {
      ar = ar + ')';
    }

    // Ensure Arabic has Tashkeel
    if (!/[\u064B-\u0652\u0670]/.test(ar)) {
      if (ar.endsWith('ة')) ar = ar.slice(0, -1) + 'َةٌ';
      else if (ar.length > 2 && !ar.includes(' ')) ar = ar + 'ٌ';
    }

    // 3. Normalize Bengali spelling
    const originalBn = bn;
    for (const [pat, repl] of BENGALI_CLEANUP_REGEXES) {
      bn = bn.replace(pat, repl);
    }
    // Clean extra whitespace
    bn = bn.replace(/\s+/g, ' ').trim();

    if (bn !== originalBn) {
      regexFixCount++;
    }
  }

  return {
    ...item,
    arabic: ar,
    bengali: bn,
    transliteration: tr,
    partOfSpeech: pos
  };
});

fs.writeFileSync(vocabPath, JSON.stringify(updatedVocab, null, 2), 'utf-8');
console.log(`Success! Applied ${overrideCount} exact overrides and ${regexFixCount} regex fixes.`);
