const cleanedVocab = vocab.map(item => {
  let ar = item.arabic.trim();
  let bn = item.bengali.trim();
  let tr = item.transliteration;
  let pos = item.partOfSpeech;

  // Check Exact Phrase Map
  const strippedAr = stripTashkeel(ar);
  let matched = false;

  for (const [key, val] of Object.entries(EXACT_PHRASE_MAP)) {
    if (ar === key || strippedAr === stripTashkeel(key)) {
      ar = val.ar;
      bn = val.bn;
      tr = val.tr;
      pos = val.pos;
      matched = true;
      break;
    }
  }

  if (!matched) {
    bn = cleanBengaliWord(bn);
    // Add harakat if noun ending without tanween or vowels
    if (!/[\u064B-\u0652\u0670]/.test(ar)) {
      // Basic noun Tashkeel
      if (ar.endsWith('ة')) ar = ar.slice(0, -1) + 'َةٌ';
      else if (ar.length > 2 && !ar.includes(' ')) ar = ar + 'ٌ';
    }
  }

  return {
    ...item,
    arabic: ar,
    bengali: bn,
    transliteration: tr,
    partOfSpeech: pos
  };
});

