const arPatterns = [
  /اإل/, /اقص/, /مهموز/, /مثال/, /أجوف/, /لفيف/, /تفعيل/,
  /\.ٌ/, /ٌ\./, /تَسَحَّرَ:/, /الحرصعلى/, /القبضعلى/, /الطمعي/, /الفوز\.أجوف/,
  /عِيادَة \. أجوف/, /العلو\.﴾ٌ/
];

const targets = [];

v.forEach(item => {
  const matchBn = bnPatterns.some(p => p.test(item.bengali));
  const matchAr = arPatterns.some(p => p.test(item.arabic));

  if (matchBn || matchAr) {
    targets.push({
      id: item.id,
      page: item.page,
      ar: item.arabic,
      bn: item.bengali,
      tr: item.transliteration,
      matchBn,
      matchAr
    });
  }
});

console.log('Total targets to cure:', targets.length);
fs.writeFileSync(path.join(__dirname, 'targets_to_cure.json'), JSON.stringify(targets, null, 2), 'utf8');
