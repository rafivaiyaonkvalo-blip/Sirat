// Clean and repair Arabic string
function sanitizeArabic(ar) {
  if (!ar) return '';
  let s = ar.trim();

  // Normalize spaces around tanween
  // Move tanween to preceding word if isolated: e.g. "جَدِيْد - ٌجَدِيْدَة" -> "جَدِيْدٌ - جَدِيْدَةٌ"
  s = s.replace(/\s*-\s*ٌ?\s*([^\s]+)/g, ' - $1');
  s = s.replace(/ٌ\s*/g, 'ٌ');
  s = s.replace(/ٌ+/g, 'ٌ');

  // Fix known corruptions from OCR/Word PDF:
  s = s.replace(/ََّلَّح ف/g, 'فَلَّاحٌ');
  s = s.replace(/ََّلَّجَة ث/g, 'ثَلَّاجَةٌ');
  s = s.replace(/ما ٌ هذا - ما ٌ ٌهذه؟/g, 'مَا هٰذَا؟ - مَا هٰذِهِ؟');
  s = s.replace(/ما ٌ ذلك - ما ٌٌ ٌتلك/g, 'مَا ذٰلِكَ؟ - مَا تِلْكَ؟');
  s = s.replace(/هذا - ٌهذه/g, 'هٰذَا - هٰذِهِ');
  s = s.replace(/ذلِك - ٌَتِلْك/g, 'ذٰلِكَ - تِلْكَ');
  s = s.replace(/جَدِيْد - ٌجَدِيْدَة/g, 'جَدِيْدٌ - جَدِيْدَةٌ');
  s = s.replace(/قَدِيْم - ٌقَدِيْمَة/g, 'قَدِيْمٌ - قَدِيْمَةٌ');
  s = s.replace(/جَمِيْل - ٌجَمِيْلَة/g, 'جَمِيْلٌ - جَمِيْلَةٌ');
  s = s.replace(/كَبِيْر - ٌكَبِيْرَة/g, 'كَبِيْرٌ - كَبِيْرَةٌ');
  s = s.replace(/صَغِيْر - ٌصَغِيْرَة/g, 'صَغِيْرٌ - صَغِيْرَةٌ');
  s = s.replace(/جَيِد - ٌجَيِدَة/g, 'جَيِّدٌ - جَيِّدَةٌ');
  s = s.replace(/نَظِيْف - ٌنَظِيْفَة/g, 'نَظِيْفٌ - نَظِيْفَةٌ');
  s = s.replace(/وَسِخ - ٌوَسِخَة/g, 'وَسِخٌ - وَسِخَةٌ');
  s = s.replace(/طِفْل - ٌطِفْلَة/g, 'طِفْلٌ - طِفْلَةٌ');
  s = s.replace(/حُجْرَة - ٌغُرْفَة/g, 'حُجْرَةٌ - غُرْفَةٌ');
  s = s.replace(/وَرَاء - ٌَخَلْف/g, 'وَرَاءَ - خَلْفَ');
  s = s.replace(/أَنْت - ٌِأَنْت/g, 'أَنْتَ - أَنْتِ');
  s = s.replace(/هُو - ٌَهِي/g, 'هُوَ - هِيَ');
  s = s.replace(/طَاز ٌج - ٌَطَاز ٌَج ٌة/g, 'طَازَجٌ - طَازَجَةٌ');
  s = s.replace(/بَائِت - ٌبَائِتَة/g, 'بَائِتٌ - بَائِتَةٌ');
  s = s.replace(/مَا مِ ٌر - ٌمَا مِ ٌر ٌة/g, 'مَاهِرٌ - مَاهِرَةٌ');
  s = s.replace(/مَاهِر - ٌمَاهِرَة/g, 'مَاهِرٌ - مَاهِرَةٌ');
  s = s.replace(/حَار - ٌحَارَّة/g, 'حَارٌّ - حَارَّةٌ');
  s = s.replace(/قَلِيْل - ٌقَل/g, 'قَلِيْلٌ - قَلِيْلَةٌ');

  // Check direct HARAKAT_FIXES
  const trimmed = s.trim();
  if (HARAKAT_FIXES[trimmed]) {
    return HARAKAT_FIXES[trimmed];
  }

  // Ensure paired words have harakat
  return s;
}

